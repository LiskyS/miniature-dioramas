import { chromium } from 'playwright-core';
const browser = await chromium.launch({ executablePath: 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe', headless: true, args: ['--disable-gpu-sandbox','--force-device-scale-factor=1','--enable-gpu'] });
const errors=[], requests=[];
let page = await browser.newPage({ viewport: { width: 1600, height: 1000 } });
page.on('pageerror', e=>errors.push(e.message)); page.on('console', m=>{if(m.type()==='error')errors.push(m.text());});
page.on('request', r=>{if(!r.url().startsWith('file://')) requests.push(r.url());});
await page.goto('file:///F:/杂活/小樽丰川邮局.html', {waitUntil:'load'});
await page.waitForFunction(()=>window.__DIORAMA__, null, {timeout:60000});
await page.waitForTimeout(10600);
const state=await page.evaluate(()=>{const d=window.__DIORAMA__;return {title:document.title, done:d.assembly.done, elapsed:+d.elapsed.toFixed(2), catVisible:d.postOffice.cat.root.visible, snow:+d.snow.material.uniforms.uOpacity.value.toFixed(2), canvases:document.querySelectorAll('canvas').length, visibleDivs:[...document.querySelectorAll('div')].filter(e=>getComputedStyle(e).display!=='none').length, minD:d.controls.minDistance, pan:d.controls.enablePan};});
await page.screenshot({path:'F:/杂活/小樽丰川邮局-预览.png'});
await page.close();
page = await browser.newPage({ viewport:{width:1600,height:1000} });
await page.goto('file:///F:/杂活/小樽丰川邮局.html?skip=1&debugtime=1', {waitUntil:'load'});
await page.waitForFunction(()=>window.__DIORAMA__, null, {timeout:60000});
await page.evaluate(()=>{const d=window.__DIORAMA__; d.controls.minDistance=0.1; d.setTime(12); d.setView([2.45,1.82,1.45],[1.55,1.78,.32]);});
await page.waitForTimeout(450);
await page.screenshot({path:'F:/杂活/小樽丰川邮局-猫咪细节.png'});
console.log(JSON.stringify({state,requests,errors},null,2));
await browser.close();
